import os
import json
import requests
import config

GEMINI_MODEL = "gemini-3.8-flash"
API_URL = f"https://generativelanguage.googleapis.com/v1beta/models/{GEMINI_MODEL}:generateContent"

SYSTEM_INSTRUCTION = """
You are an elite Chief Marketing Officer (CMO) and Brand Strategist.
Your job is to analyze the day's top news stories across Advertising, Branding, and Marketing, and produce high-level strategic intelligence.

Return your response strictly in valid JSON matching this schema:
{
  "executive_summary": "A 2-3 sentence strategic pulse summarizing the macro trends impacting marketing leaders today.",
  "strategic_themes": [
    "Theme 1 (e.g. Agentic AI in Creative Suites): Explanation of the shift...",
    "Theme 2 (e.g. Identity & Rebrand Overhauls): Explanation of the shift...",
    "Theme 3 (e.g. Media Allocation & Retail Networks): Explanation of the shift..."
  ],
  "article_insights": [
    {
      "id": 0,
      "strategic_takeaway": "One sharp sentence explaining why this specific move matters to brand directors or competitors."
    }
  ]
}
"""

def analyze_with_ai(articles: list) -> dict:
    """
    Sends the curated news stories to Gemini to generate strategic executive insights,
    macro themes, and individual article takeaways.
    """
    api_key = config.GEMINI_API_KEY or os.getenv("GEMINI_API_KEY", "").strip()

    if not api_key:
        print("[AI Analyst] ⚠️ No GEMINI_API_KEY found. Using heuristic synthesis fallback.")
        return None

    # Prepare compact representation for prompt
    articles_data = []
    for idx, a in enumerate(articles[:18]):
        articles_data.append({
            "id": idx,
            "title": a.get("title", ""),
            "source": a.get("source", ""),
            "category": a.get("category", ""),
            "summary": a.get("summary", "")[:200]
        })

    prompt_content = f"""
{SYSTEM_INSTRUCTION}

Here are today's top curated news stories:
{json.dumps(articles_data, indent=2)}

Output strictly valid JSON only without markdown code blocks.
"""

    payload = {
        "contents": [
            {
                "parts": [{"text": prompt_content}]
            }
        ],
        "generationConfig": {
            "responseMimeType": "application/json",
            "temperature": 0.3
        }
    }

    try:
        print(f"[AI Analyst] 🧠 Analyzing {len(articles_data)} stories with Gemini AI ({GEMINI_MODEL})...")
        resp = requests.post(
            f"{API_URL}?key={api_key}",
            json=payload,
            headers={"Content-Type": "application/json"},
            timeout=35
        )

        if resp.status_code != 200:
            print(f"[AI Analyst] ❌ Gemini API returned HTTP {resp.status_code}: {resp.text[:150]}")
            return None

        result = resp.json()
        raw_text = result["candidates"][0]["content"]["parts"][0]["text"].strip()
        
        # Clean potential markdown wrapping if returned
        if raw_text.startswith("```json"):
            raw_text = raw_text[7:]
        if raw_text.startswith("```"):
            raw_text = raw_text[3:]
        if raw_text.endswith("```"):
            raw_text = raw_text[:-3]

        parsed = json.loads(raw_text.strip())
        print("[AI Analyst] ✅ Strategic synthesis successfully generated by Gemini AI!")
        return parsed

    except Exception as e:
        print(f"[AI Analyst] ⚠️ AI analysis failed or timed out: {e}. Falling back to rule-based synthesis.")
        return None
